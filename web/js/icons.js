export function iconFor(entry) {
  if (entry.type === 'dir') return 'folder';
  const e = entry.ext || '';
  if (/^(png|jpe?g|gif|webp|svg|bmp|ico|avif)$/.test(e)) return 'image';
  if (/^(md|txt|rst|log|csv)$/.test(e)) return 'file-text';
  if (/^(js|mjs|cjs|ts|tsx|jsx|py|go|rs|java|cs|rb|php|sh|ps1|json|yml|yaml|toml|html|css|scss|sql|c|cpp|h|kt|swift|vue|svelte|xml)$/.test(e)) return 'file-code';
  return 'file';
}
